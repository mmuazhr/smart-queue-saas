// =============================================================================
// NextAuth v5 (Auth.js) — Edge-safe Configuration
// =============================================================================
// Shared by the edge middleware and the Node runtime config in ./auth.
// Must not import bcryptjs, prisma, pg, or any Node built-in.

import type { NextAuthConfig } from "next-auth";

export const authConfig = {
  providers: [],
  callbacks: {
    async jwt({ token, user }) {
      if (user) {
        token.id = user.id;
        token.role = (user as { role: string }).role;
      }
      return token;
    },
    async session({ session, token }) {
      if (session.user) {
        session.user.id = token.id as string;
        session.user.role = token.role as string;
      }
      return session;
    },
  },
  pages: {
    signIn: "/login",
  },
  session: {
    strategy: "jwt",
  },
} satisfies NextAuthConfig;
